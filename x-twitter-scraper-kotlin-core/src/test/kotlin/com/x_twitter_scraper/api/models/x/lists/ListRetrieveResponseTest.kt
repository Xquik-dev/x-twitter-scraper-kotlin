        val listRetrieveResponse =
            ListRetrieveResponse.builder()
                .list(
                    ListRetrieveResponse.XList.builder()
                        .id("id")
                        .name("name")
                        .bannerUrl("bannerUrl")
                        .createdAt(OffsetDateTime.parse("2019-12-27T18:11:19.117Z"))
                        .customBanner(
                            ListRetrieveResponse.XList.CustomBanner.builder()
