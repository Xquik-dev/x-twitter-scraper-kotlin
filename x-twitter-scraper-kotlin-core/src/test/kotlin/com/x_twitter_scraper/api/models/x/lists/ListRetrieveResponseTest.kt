                                    ListRetrieveResponse.XList.CustomBanner.Palette.builder()
                                        .percentage(0.0)
                                        .rgb(
                                            ListRetrieveResponse.XList.CustomBanner.Palette.Rgb
                                                .builder()
                                                .blue(0L)
                                                .green(0L)
                                                .red(0L)
                                                .build()
                                        )
                                        .build()
                                )
                                .salientRect(
                                    ListRetrieveResponse.XList.CustomBanner.SalientRect.builder()
                                        .height(0L)
                                        .left(0L)
                                        .top(0L)
                                        .width(0L)
                                        .build()
                                )
                                .width(0L)
                                .build()
                        )
                        .defaultBanner(
                            ListRetrieveResponse.XList.DefaultBanner.builder()
                                .url("url")
                                .height(0L)
                                .mediaId("mediaId")
                                .mediaKey("mediaKey")
                                .addPalette(
                                    ListRetrieveResponse.XList.DefaultBanner.Palette.builder()
                                        .percentage(0.0)
                                        .rgb(
                                            ListRetrieveResponse.XList.DefaultBanner.Palette.Rgb
                                                .builder()
                                                .blue(0L)
                                                .green(0L)
                                                .red(0L)
                                                .build()
                                        )
                                        .build()
                                )
                                .salientRect(
                                    ListRetrieveResponse.XList.DefaultBanner.SalientRect.builder()
                                        .height(0L)
                                        .left(0L)
                                        .top(0L)
                                        .width(0L)
                                        .build()
                                )
                                .width(0L)
                                .build()
                        )
                        .description("description")
                        .addFacepileUrl("facepileUrl")
                        .memberCount(0L)
