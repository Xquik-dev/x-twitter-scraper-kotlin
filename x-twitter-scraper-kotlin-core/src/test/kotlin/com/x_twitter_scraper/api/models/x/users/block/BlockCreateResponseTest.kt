                .result(
                    BlockCreateResponse.Result.builder()
                        .id("id")
                        .state("state")
                        .type(BlockCreateResponse.Result.Type.TWEET)
                        .build()
                )
                .retryable(true)
                .safeToRetry(true)
                .sendDispatched(true)
                .status(BlockCreateResponse.Status.ACCEPTED)
