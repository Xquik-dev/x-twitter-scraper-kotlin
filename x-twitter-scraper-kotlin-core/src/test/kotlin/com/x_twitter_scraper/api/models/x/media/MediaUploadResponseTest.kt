        val mediaUploadResponse =
            MediaUploadResponse.builder()
                .id("id")
                .account(
                    MediaUploadResponse.Account.builder().id("id").username("username").build()
                )
                .action(MediaUploadResponse.Action.CREATE_TWEET)
