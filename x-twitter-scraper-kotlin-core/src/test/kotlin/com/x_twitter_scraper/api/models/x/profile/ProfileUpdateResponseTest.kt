                .result(
                    ProfileUpdateResponse.Result.builder()
                        .id("id")
                        .state("state")
                        .type(ProfileUpdateResponse.Result.Type.TWEET)
                        .build()
                )
                .retryable(true)
                .safeToRetry(true)
                .sendDispatched(true)
                .status(ProfileUpdateResponse.Status.ACCEPTED)
