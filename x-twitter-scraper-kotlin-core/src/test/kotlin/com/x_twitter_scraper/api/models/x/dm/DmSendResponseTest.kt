                    DmSendResponse.Result.builder()
                        .id("id")
                        .state("state")
                        .type(DmSendResponse.Result.Type.TWEET)
                        .build()
                )
                .retryable(true)
                .safeToRetry(true)
                .sendDispatched(true)
                .status(DmSendResponse.Status.ACCEPTED)
