                                .putAdditionalProperty("foo", JsonValue.from("bar"))
                                .build()
                        )
                        .build()
                )
                .result(
                    DmSendResponse.Result.builder()
                        .id("id")
                        .state("state")
                        .type(DmSendResponse.Result.Type.TWEET)
                        .build()
