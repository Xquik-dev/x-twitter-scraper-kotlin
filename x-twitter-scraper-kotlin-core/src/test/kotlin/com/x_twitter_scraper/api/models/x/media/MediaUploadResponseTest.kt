                    MediaUploadResponse.NextAction.builder()
                        .type(MediaUploadResponse.NextAction.Type.POLL)
                        .afterMs(0L)
                        .requiresNewIdempotencyKey(true)
                        .url("url")
                        .build()
                )
                .pollAfterMs(0L)
                .request(
                    MediaUploadResponse.Request.builder()
                        .hash("hash")
                        .payload(
                            MediaUploadResponse.Request.Payload.builder()
                                .putAdditionalProperty("foo", JsonValue.from("bar"))
                                .build()
                        )
                        .build()
                )
                .result(
                    MediaUploadResponse.Result.builder()
                        .id("id")
                        .state("state")
                        .type(MediaUploadResponse.Result.Type.TWEET)
                        .build()
                )
                .retryable(true)
                .safeToRetry(true)
                .sendDispatched(true)
                .status(MediaUploadResponse.Status.ACCEPTED)
                .statusUrl("statusUrl")
                .success(true)
                .target(
                    MediaUploadResponse.Target.builder()
                        .id("id")
                        .type(MediaUploadResponse.Target.Type.TWEET)
                        .build()
                )
                .targetId("targetId")
                .terminal(true)
                .writeActionId("writeActionId")
                .communityId("communityId")
                .communityName("communityName")
                .completedAt(OffsetDateTime.parse("2019-12-27T18:11:19.117Z"))
                .confirmationAttempts(0L)
                .confirmationCheckedAt(OffsetDateTime.parse("2019-12-27T18:11:19.117Z"))
