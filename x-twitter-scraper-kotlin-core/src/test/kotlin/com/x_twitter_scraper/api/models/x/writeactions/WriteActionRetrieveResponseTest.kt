                        .type(WriteActionRetrieveResponse.Result.Type.TWEET)
                        .build()
                )
                .retryable(true)
                .safeToRetry(true)
                .sendDispatched(true)
                .status(WriteActionRetrieveResponse.Status.ACCEPTED)
